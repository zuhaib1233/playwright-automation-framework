import { Page, Locator } from '@playwright/test';
import { BasePage } from './base.page';

export class ChannelsPage extends BasePage {
  readonly addChannelButton: Locator;
  readonly searchInput: Locator;

  // Add Channel Form Controls
  readonly channelNumberInput: Locator;
  readonly channelNameInput: Locator;
  readonly saveChannelButton: Locator;
  readonly swalConfirmButton: Locator;

  constructor(page: Page) {
    super(page);

    this.addChannelButton = page.locator('button:has-text("Add channel"), a:has-text("Add channel")');
    this.searchInput = page.locator('input[placeholder*="Search channels"]');

    this.channelNumberInput = page.locator('input[placeholder*="251"], label:has-text("Number") ~ input, input[name="number"]').first();
    this.channelNameInput = page.locator('input[placeholder*="Nektos News HD"], label:has-text("Name") ~ input, input[name="name"]').first();
    this.saveChannelButton = page.locator('button:has-text("Save channel"), input[value="Save channel"]').last();
    this.swalConfirmButton = page.locator('.swal2-confirm, button:has-text("OK")');
  }

  async navigateToChannels() {
    await this.navigateTo('/live-tv');
  }

  async clickAddChannel() {
    await this.clickElement(this.addChannelButton);
  }

  async getAutoGeneratedNumber(): Promise<string> {
    await this.channelNumberInput.waitFor({ state: 'visible' });
    return await this.channelNumberInput.inputValue();
  }

  async fillMandatoryDetailsAndSave(channelName: string) {
    await this.fillText(this.channelNameInput, channelName);

    await this.saveChannelButton.scrollIntoViewIfNeeded();
    await this.saveChannelButton.click();

    try {
      await this.swalConfirmButton.waitFor({ state: 'visible', timeout: 5000 });
      await this.swalConfirmButton.click();
    } catch {
      // Auto-dismiss or toast ignored
    }
  }

  async verifyChannelInGrid(channelName: string): Promise<Locator> {
    await this.searchInput.waitFor({ state: 'visible' });
    await this.searchInput.fill(channelName);
    await this.page.keyboard.press('Enter');

    const row = this.page.locator(`tr:has-text("${channelName}"), div:has-text("${channelName}")`).first();
    await row.waitFor({ state: 'visible', timeout: 10000 });
    return row;
  }

  
  // Strictly delete test automation channel using direct URL query & DOM click
  // Strictly delete test automation channel by EXACT Number & Name
  async deleteTestChannelStrictly(channelNumber: string, channelName: string): Promise<boolean> {
    await this.page.setViewportSize({ width: 1920, height: 1080 });
    await this.navigateToChannels();
    await this.page.waitForLoadState('networkidle').catch(() => {});
    await this.page.waitForTimeout(1000);

    // 1. Search input dhoondein (table ke upar wala input)
    const tableSearch = this.page.locator('input[placeholder*="Search channels"], input[placeholder*="Search"]').last();
    await tableSearch.waitFor({ state: 'visible', timeout: 10000 });
    
    // Clear existing text
    await tableSearch.click();
    await tableSearch.fill('');
    await this.page.waitForTimeout(300);

    // Channel name fill karein
    await tableSearch.fill(channelName);
    await tableSearch.dispatchEvent('input');
    
    // Sirf is specific input field par Enter press karein (global form submit se bachne ke liye)
    await tableSearch.press('Enter');
    await this.page.waitForTimeout(2000);

    // 2. Agar "Import channels from M3U" modal khul jaye, toh foran close karein
    const modalCancelBtn = this.page.locator('button:has-text("Cancel"), button[aria-label="Close"], .modal button:has-text("×")');
    if (await modalCancelBtn.first().isVisible({ timeout: 1000 }).catch(() => false)) {
      console.log('Dismissing accidental M3U modal...');
      await modalCancelBtn.first().click();
      await this.page.waitForTimeout(1000);
    }

    // 3. Filtered Row verify karein: Table row jisme channel number ho
    const targetRow = this.page.locator('tbody tr')
      .filter({ hasText: channelNumber })
      .first();

    await targetRow.waitFor({ state: 'visible', timeout: 10000 });
    console.log(`Locked target row for channel #${channelNumber}.`);

    // 4. Trash Button Click: Row ke andar pencil ke baad wala delete icon
    // Aakhri td mein trash icon find karein
    const actionCell = targetRow.locator('td').last();
    const deleteBtn = actionCell.locator('button, a, svg, i').last();

    await deleteBtn.scrollIntoViewIfNeeded();

    // DOM-level click trigger karein
    await deleteBtn.evaluate((el: HTMLElement) => el.click()).catch(async () => {
      await deleteBtn.click({ force: true });
    });
    console.log(`Triggered delete click on row #${channelNumber}.`);

    // 5. SweetAlert2 Confirmation Dialog
    const confirmBtn = this.page.locator('.swal2-confirm, button:has-text("Yes"), button:has-text("Delete")').first();
    await confirmBtn.waitFor({ state: 'visible', timeout: 8000 });
    await confirmBtn.click();
    console.log('Confirmed delete modal dialog.');

    // Secondary Success popup (agar show ho)
    try {
      const okBtn = this.page.locator('.swal2-confirm, button:has-text("OK")').first();
      await okBtn.waitFor({ state: 'visible', timeout: 3000 });
      await okBtn.click();
    } catch {
      // toast auto-close
    }

    await this.page.locator('.swal2-container').waitFor({ state: 'hidden', timeout: 5000 }).catch(() => {});
    await this.page.waitForTimeout(1500);
    return true;
  }
}