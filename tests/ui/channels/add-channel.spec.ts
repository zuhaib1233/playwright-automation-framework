import { test, expect } from '../../../src/fixtures/testFixtures';
import { saveTestChannel } from '../../../src/utils/jsonHelper';
import * as dotenv from 'dotenv';
import path from 'path';

dotenv.config({ path: path.resolve(process.cwd(), '.env') });

test.describe('Optix IPTV - Channels Management', () => {
  test.beforeEach(async ({ loggedInUser, channelsPage }) => {
    await channelsPage.navigateToChannels();
  });

  test('TC-CH-001: Should create channel and record to JSON', async ({ channelsPage, page }) => {
    // 1. "+ Add channel" click karein
    await channelsPage.clickAddChannel();
    await expect(page).toHaveURL(/.*channel-editor/i, { timeout: 10000 });

    // 2. Auto-generated number fetch karein
    const autoNumber = await channelsPage.getAutoGeneratedNumber();
    console.log(`Auto assigned channel number: ${autoNumber}`);

    // 3. Unique Channel Name
    const uniqueId = Date.now().toString().slice(-4);
    const testChannelName = `Optix Automation ${autoNumber}-${uniqueId}`;

    // 4. Details fill karke save karein
    await channelsPage.fillMandatoryDetailsAndSave(testChannelName);

    // 5. Success confirm hone par JSON me save karein
    saveTestChannel({
      number: autoNumber,
      name: testChannelName,
      createdAt: new Date().toISOString()
    });
    console.log(`Saved channel ${autoNumber} into test-channels.json`);

    // 6. Grid me return aur verification
    await channelsPage.navigateToChannels();
    const row = await channelsPage.verifyChannelInGrid(testChannelName);
    await expect(row).toBeVisible();
  });
});